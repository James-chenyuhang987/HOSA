import type { Phrase } from './hospitalLexicon'
import type { Direction, Translation } from './translationTypes'
import { endingFor, prepareForMatch, stripEnding } from './translationMatching'
import { durationPattern as duration, onsetPattern as onset, timeScopePattern as timeScope } from './hospitalTime'

// These are complete, positive symptom statements, not arbitrary replacement
// slots. Unknown symptoms, negation, uncertainty and degree words cannot match.
const symptoms = new Set([
  '我头痛', '我头晕', '我咳嗽', '我拉肚子', '我呼吸困难', '我胸口痛',
  '我肚子痛', '我喉咙痛', '我皮肤痒', '我左边肚子痛', '我右边肚子痛',
])
// Time scopes wrap only an explicitly listed complete statement. In particular,
// negation/uncertainty stays INSIDE the translated phrase and is never rebuilt
// from a positive symptom. Completed events retain their “already” wording.
const timedStatements = new Set([
  ...symptoms, '我胸口有点痛', '我胸口很痛', '我想吐', '我恶心想吐', '我已经吐了',
  '我没有发烧', '我没有咳嗽', '我没有呕吐', '我还没有吃药',
  '我吃药后起了皮疹', '我吃药后症状加重了', '我不确定对这个药是否过敏',
  '我对这个药过敏', '我可能怀孕了', '我没有怀孕', '我正在哺乳',
])
// A symptom cannot absorb a separate question/sentence whose punctuation the
// exact lookup would otherwise trim away (e.g. “我头痛？三天了”).
const symptomText = '[^，,。！？!?；;:：\\n]+?'
const durationInput = new RegExp(`^(${symptomText})[，,]?(?:已经|已經)?(${duration})了$`, 'u')
const alreadyInput = new RegExp(`^我(?:已经|已經)(${symptomText})[，,]?(${duration})了$`, 'u')
const onsetInput = new RegExp(`^我(?:从|從)?(${onset})(?:开始|開始)(${symptomText})$`, 'u')
const durationOutput = new RegExp(`^(${symptomText})[，,](?:症状时长|症狀時長)[:：](${duration})$`, 'u')
const onsetOutput = new RegExp(`^(${symptomText})[，,](?:开始时间|開始時間)[:：](${onset})$`, 'u')
// A stored statement may have an internal comma (“我作呕，想呕”), but may
// not swallow a separate sentence or another labelled qualifier.
const statementText = '[^。！？!?；;:：\\n]+?'
const subjectScopeInput = new RegExp(`^我(${timeScope})(${statementText})$`, 'u')
const leadingScopeInput = new RegExp(`^(${timeScope})[，,]?(我${statementText})$`, 'u')
const scopeOutput = new RegExp(`^(${statementText})[，,](?:时间范围|時間範圍)[:：](${timeScope})$`, 'u')

// Use a shared written time qualifier rather than inventing unreviewed dialect
// grammar. The original amount, unit and relative time are copied, never inferred
// or converted. The UI identifies this separately from a fixed whole phrase.
export function translateHospitalPattern(
  source: string, direction: Direction, lookup: (text: string) => Phrase | null,
): Translation | null {
  const input = stripEnding(prepareForMatch(source))
  type Candidate = { statement: string; value: string; kind: 'duration' | 'onset' | 'scope' }
  const candidates: Candidate[] = []
  let match = durationInput.exec(input)
  if (match) candidates.push({ statement: match[1], value: match[2], kind: 'duration' })
  match = alreadyInput.exec(input)
  if (match) candidates.push({ statement: `我${match[1]}`, value: match[2], kind: 'duration' })
  match = onsetInput.exec(input)
  if (match) candidates.push({ statement: `我${match[2]}`, value: match[1], kind: 'onset' })
  match = subjectScopeInput.exec(input)
  if (match) candidates.push({ statement: `我${match[2]}`, value: match[1], kind: 'scope' })
  match = leadingScopeInput.exec(input)
  if (match) candidates.push({ statement: match[2], value: match[1], kind: 'scope' })
  // Also accept the structured sentence generated by this module, for swapping
  // directions or pasting it back. All of the qualifier must be present.
  match = durationOutput.exec(input)
  if (match) candidates.push({ statement: match[1], value: match[2], kind: 'duration' })
  match = onsetOutput.exec(input)
  if (match) candidates.push({ statement: match[1], value: match[2], kind: 'onset' })
  match = scopeOutput.exec(input)
  if (match) candidates.push({ statement: match[1], value: match[2], kind: 'scope' })
  const candidate = candidates.map((item) => ({ ...item, phrase: lookup(item.statement) }))
    .find((item) => item.phrase && (item.kind === 'scope' ? timedStatements : symptoms).has(item.phrase.source))
  if (!candidate?.phrase) return null
  const { phrase, kind, value } = candidate
  const qualifier = kind === 'duration' ? '症状时长' : kind === 'onset' ? '开始时间' : '时间范围'
  const text = direction === 'toDialect' ? `${stripEnding(phrase.text)}，${qualifier}：${value}`
    : kind === 'duration' ? `${phrase.source}${value}了`
      : kind === 'onset' ? `我从${value}开始${phrase.source.slice(1)}` : `我${value}${phrase.source.slice(1)}`
  return {
    text: text + endingFor(source),
    confidence: 'template',
    pronunciation: '',
    note: `${kind === 'scope' ? '时间范围只限定本句，不代表症状的开始时间；否定和不确定语气沿用已收录的完整短句。' : '症状使用已收录短句，时长或开始时间用书面语单独列出。'}保留原文数值、单位、约数和相对时间，不推算日期或判断是否持续发作。仅支持部分明确句式，方言表达和时间请让医护人员核对。`,
  }
}
